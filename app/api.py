from typing import List, Optional
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel, Field

from app.evaluator import AIQualityEvaluator

app = FastAPI(
    title="Atomberg AI Quality Evaluation & Regression Platform",
    description="REST API for evaluating LLM responses on Accuracy, Relevance, Groundedness, and Hallucinations.",
    version="1.0.0",
)

# Initialize a default reusable evaluator instance
evaluator = AIQualityEvaluator(pass_threshold=0.70, groundedness_threshold=0.60)


class EvaluationRequest(BaseModel):
    """Pydantic schema for validating incoming single-case evaluation requests."""
    id: Optional[str] = Field(default="LIVE-001", description="Unique identifier for the test case")
    category: Optional[str] = Field(default="live_check", description="Feature category")
    prompt: str = Field(..., min_length=1, description="User question sent to the AI")
    context: str = Field(..., min_length=1, description="Retrieved ground-truth knowledge base text")
    expected_output: str = Field(..., min_length=1, description="Reference expected response")
    expected_keywords: List[str] = Field(default_factory=list, description="Must-have ground-truth terms")
    actual_output: str = Field(..., min_length=1, description="Actual response generated by the AI")


@app.get("/health")
def health_check():
    """Health check endpoint to verify the evaluation service is online."""
    return {
        "status": "healthy",
        "service": "ai-quality-evaluation-platform",
        "pass_threshold": evaluator.pass_threshold,
        "groundedness_threshold": evaluator.groundedness_threshold,
    }


@app.post("/evaluate")
def evaluate_single_response(payload: EvaluationRequest):
    """
    Evaluates a single AI response in real time and flags hallucinations.
    """
    case_dict = payload.model_dump()
    result = evaluator.evaluate_case(case_dict)
    return result


@app.get("/evaluate/dataset")
def evaluate_golden_dataset():
    """
    Runs regression evaluation across the entire Golden Dataset JSON file.
    """
    try:
        return evaluator.evaluate_dataset("datasets/golden_dataset.json")
    except FileNotFoundError as exc:
        raise HTTPException(status_code=404, detail=str(exc))
